"""Work out which MIUI libraries MIUI Camera needs that LineageOS does not ship, and stage them.

Walks ELF DT_NEEDED from the camera's JNI libs plus library names found as strings in the APK
(System.loadLibrary / dlopen targets). A library already present in the LineageOS file list stops
the walk; anything else is resolved in the MIUI dump, staged into miui-ports/MiuiCamera/deps/ and
listed in deps.mk with the same partition path it had on MIUI.

Usage: python -I scripts/miuicamera-deps.py <miui_files_dir> <los_file_list> <module_dir>
"""
import re
import shutil
import sys
import zipfile
from pathlib import Path

LIB_RE = re.compile(rb"lib[A-Za-z0-9_.+\-@]+\.so")
# Provided by APEX modules (runtime, ART), which the partition file list does not include.
APEX_LIBS = {"libc.so", "libm.so", "libdl.so", "libnativehelper.so"}
# Generic AOSP libraries the platform builds on demand. The stock image may not ship them (so they
# are absent from the file list), but copying a prebuilt collides with Soong's own install rule.
PLATFORM_ON_DEMAND = {"libhidltransport.so"}
PARTITION_VAR = {
    "system": "$(TARGET_COPY_OUT_SYSTEM)",
    "system_ext": "$(TARGET_COPY_OUT_SYSTEM_EXT)",
    "product": "$(TARGET_COPY_OUT_PRODUCT)",
    "vendor": "$(TARGET_COPY_OUT_VENDOR)",
    "odm": "$(TARGET_COPY_OUT_ODM)",
}


def load_elf_needed():
    # The sibling script's file name has dashes, so it cannot be imported normally.
    src = (Path(__file__).parent / "pull-miuicamera-deps.py").read_text(encoding="utf-8")
    ns = {"__name__": "deps"}
    exec(compile(src.split("def main")[0], "pull-miuicamera-deps.py", "exec"), ns)
    return ns["elf_needed"]


def main():
    files_dir, los_list, module_dir = (Path(a) for a in sys.argv[1:4])
    elf_needed = load_elf_needed()

    # A system app's linker namespace cannot see /vendor or /odm libraries, so only system-side copies count.
    los_libs = {l.rsplit("/", 1)[1] for l in los_list.read_text(encoding="utf-8").split()
                if "/lib64/" in l and l.split("/")[1] in ("system", "system_ext", "product")}
    los_libs |= APEX_LIBS | PLATFORM_ON_DEMAND
    miui = {}
    for p in files_dir.rglob("*.so"):
        rel = "/" + p.relative_to(files_dir).as_posix()
        if "/lib64/" in rel and "/priv-app/" not in rel and "/app/" not in rel:
            miui.setdefault(p.name, []).append((rel, p))

    app_dir = module_dir / "lib" / "arm64"
    queue = [(p.name, p, "jni") for p in app_dir.glob("*.so")]
    with zipfile.ZipFile(module_dir / "MiuiCamera.apk") as z:
        for n in z.namelist():
            if n.endswith(".dex"):
                for m in set(LIB_RE.findall(z.read(n))):
                    queue.append((m.decode(), None, "apk-string"))

    needed, missing, seen = {}, {}, set()
    while queue:
        name, path, why = queue.pop()
        if name in seen:
            continue
        seen.add(name)
        if path is None:
            if name in los_libs:
                continue
            hits = miui.get(name)
            if not hits:
                missing[name] = why
                continue
            rel, path = sorted(hits)[0]
            needed[rel] = (path, why)
        for dep in elf_needed(path.read_bytes()):
            if dep not in seen:
                queue.append((dep, None, name))

    # Data files the app reads directly: MIUI's per-device feature list and camera configs LineageOS lacks.
    los_files = set(los_list.read_text(encoding="utf-8").split())
    for pattern in ("product/etc/device_features/*.xml", "vendor/etc/camera/**/*"):
        for p in files_dir.glob(pattern):
            rel = "/" + p.relative_to(files_dir).as_posix()
            if p.is_file() and rel not in los_files:
                needed[rel] = (p, "data")

    deps_dir = module_dir / "deps"
    if deps_dir.exists():
        shutil.rmtree(deps_dir)
    lines = ["# Generated by scripts/miuicamera-deps.py: MIUI libraries MIUI Camera loads that LineageOS lacks.",
             "PRODUCT_COPY_FILES += \\"]
    for rel, (path, why) in sorted(needed.items()):
        part, sub = rel.lstrip("/").split("/", 1)
        dest = deps_dir / part / sub
        dest.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(path, dest)
        lines.append(f"    $(MIUICAMERA_DIR)deps/{part}/{sub}:{PARTITION_VAR[part]}/{sub} \\")
    lines[-1] = lines[-1].rstrip(" \\")
    (module_dir / "deps.mk").write_text("\n".join(lines) + "\n", encoding="utf-8")

    report = ["# MIUI Camera dependency report", "", f"Staged {len(needed)} libraries:", ""]
    report += [f"- `{rel}` (needed by {why})" for rel, (_, why) in sorted(needed.items())]
    report += ["", f"Not found in MIUI or LineageOS ({len(missing)}), usually harmless string matches:", ""]
    report += [f"- `{n}` ({w})" for n, w in sorted(missing.items())]
    (module_dir / "deps-report.txt").write_text("\n".join(report) + "\n", encoding="utf-8")
    print(f"staged {len(needed)}, unresolved {len(missing)}")


if __name__ == "__main__":
    main()
